export const payrollRecords = staffMembers.map((staff, index) => {
  const grossPay = Math.round(staff.salary / 12);
  const deductions = Math.round(grossPay * (index === 8 ? 0.11 : 0.25));
  return {
    id: `pr-${String(index + 1).padStart(3, "0")}`,
    staffId: staff.id,
    staffName: staff.name,
    role: staff.role,
    department: staff.department,
    hoursWorked: index === 8 ? 0 : 168 + (index % 3) * 4,
    grossPay,
    totalDeductions: deductions,
    netPay: grossPay - deductions,
    payPeriod: "August 2026",
    status: index === 5 ? "processing" : index === 8 ? "pending" : "paid",
    libraryId: staff.libraryId,
  };
});

